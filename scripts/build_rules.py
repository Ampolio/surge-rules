#!/usr/bin/env python3
"""Build and validate reviewed Surge rules. No network access or third-party packages."""
import argparse
import fnmatch
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = ["Claude.list", "Claude-Artifacts.list", "Claude-Shared-Services.list",
              "Claude-Telemetry.list", "Claude-Developer-Extras.list"]
DOMAIN = re.compile(r"(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}\Z")

def lines(name):
    return [s.strip() for s in (ROOT / name).read_text(encoding="utf-8").splitlines()
            if s.strip() and not s.lstrip().startswith("#")]

def rules(name):
    result = []
    for line in lines(name):
        fields = line.split(",")
        assert len(fields) == 2, (name, line)
        kind, value = fields
        assert kind in ("DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-WILDCARD"), line
        assert DOMAIN.fullmatch(value.replace("*", "sample")), line
        assert ("*" not in value) or kind == "DOMAIN-WILDCARD", line
        result.append((kind, value))
    assert len(result) == len(set(result)), ("Duplicate", name)
    return result

def covers(rule, pattern):
    kind, value = rule
    if kind == "DOMAIN-SUFFIX":
        return pattern == value or pattern.endswith("." + value)
    if kind == "DOMAIN":
        return pattern == value
    # A wildcard source pattern must itself be covered, not merely one test host.
    return pattern == value or ("*" not in pattern and fnmatch.fnmatchcase(pattern, value))

def matched(profile, host):
    return any(covers(rule, host.lower().rstrip(".")) for rule in profile)

def expected():
    parts = {name: rules(name) for name in COMPONENTS}
    merged = [rule for name in COMPONENTS for rule in parts[name]]
    assert len(merged) == len(set(merged)), "Duplicate across component files"
    header = ["# Claude / Anthropic - extended Surge RULE-SET",
              "# Reviewed: 2026-10-16 (Asia/Singapore)",
              "# GENERATED by scripts/build_rules.py; edit component files instead.",
              "# Includes shared third-party hosts. See README.md and SOURCES.md.",
              "# Requires DOMAIN-WILDCARD support. No policy inside this file.", ""]
    for name, entries in parts.items():
        header += ["# " + name] + [",".join(r) for r in entries] + [""]
    return parts, merged, "\n".join(header)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate without writing")
    args = parser.parse_args()
    parts, merged, generated = expected()
    target = ROOT / "Claude-Extended.list"
    if not args.check:
        target.write_text(generated, encoding="utf-8")
    assert target.read_text(encoding="utf-8") == generated, "Stale extended list"
    core = parts["Claude.list"]
    assert len(core) == 10 and len(merged) == 26
    domainset = [("DOMAIN-SUFFIX", s[1:]) if s.startswith(".") else ("DOMAIN", s)
                 for s in lines("Claude.domainset")]
    assert core == domainset, "DOMAIN-SET differs from main rules"
    # Detect a broader rule swallowing another rule.
    for i, rule in enumerate(merged):
        for j, other in enumerate(merged):
            assert i == j or not covers(rule, other[1]), ("Redundant", rule, other)
    audit = json.loads((ROOT / "audit/coverage.json").read_text(encoding="utf-8"))
    for source in audit["sources"]:
        profile = core if source["profile"] == "main" else merged
        missing = [p for p in source["patterns"] if not any(covers(r, p) for r in profile)]
        assert not missing, (source["id"], missing)
        print("PASS {}: {}/{} reviewed patterns".format(
            source["id"], len(source["patterns"]), len(source["patterns"])))
    for host in ["x.livepreview.claude.app", "a.b.claudemcpcontent.com",
                 "assets-proxy.anthropic.com", "API.ANTHROPIC.COM."]:
        assert matched(core, host), host
    for host in ["fonts.googleapis.com", "unpkg.com", "chromium-review.googlesource.com"]:
        assert matched(merged, host) and not matched(core, host), host
    for host in ["notclaude.ai", "claude.app.attacker.example", "other.b-cdn.net",
                 "sub.servd-anthropic-website.b-cdn.net", "other.googleapis.com",
                 "www.googlesource.com", "www.sentry.io", "example.com"]:
        assert not matched(merged, host), host
    print("PASS: 10 main rules; 26 extended rules; format, union, parity and matching boundaries")

if __name__ == "__main__":
    main()
